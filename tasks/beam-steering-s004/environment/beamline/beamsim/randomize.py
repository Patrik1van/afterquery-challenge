"""Domain randomization for TT20 transfer line (Adam Štafa report §1.1 & Table 1).

Applies model mismatch so the episode runs on a perturbed beamline while the agent
and reference work with the nominal model.

Table 1 "medium" spreads:
- Corrector gains: +/- 2% per corrector (log-normal: exp(N(0, 0.02^2)))
- Initial beta_x0: +/- 50% (log-normal: exp(N(0, 0.50^2)))
- Initial beta_y0: +/- 10% (log-normal: exp(N(0, 0.10^2)))
- Initial alpha_x0: +/- 1.0 (additive normal: N(0, 1.0^2))
- Initial alpha_y0: +/- 0.3 (additive normal: N(0, 0.3^2))
- Geometric emittance: +/- 20% (log-normal: exp(N(0, 0.20^2)))
- Background level nu: +/- 40% (log-normal: exp(N(0, 0.40^2)))

Note on quadrupole gradients:
As instructed in the project plan, quadrupole gradient errors are skipped here;
beta-beating is generated by transporting perturbed initial (beta_0, alpha_0) Twiss
parameters through the nominal transfer matrices M(0 -> s).
"""

from __future__ import annotations

from dataclasses import dataclass
import numpy as np
from scipy.special import ndtr

from beamsim.lattice import Lattice, PlaneLattice


@dataclass
class PerturbedPlane:
    """Perturbed optical parameters and gains for one plane."""
    plane: str
    beta_corr: np.ndarray      # (n_corr,)
    alpha_corr: np.ndarray     # (n_corr,)
    mu_corr: np.ndarray        # (n_corr,)
    beta_sem: np.ndarray       # (n_sem,)
    alpha_sem: np.ndarray      # (n_sem,)
    mu_sem: np.ndarray         # (n_sem,)
    beta_ap: np.ndarray        # (K,)
    alpha_ap: np.ndarray       # (K,)
    mu_ap: np.ndarray          # (K,)
    sigma_sem: np.ndarray      # (n_sem,)
    foil_length: np.ndarray    # (n_sem,)
    i_max: np.ndarray          # (n_sem,)
    corrector_gains: np.ndarray # (n_corr,) gain multiplier g_j (nominal 1.0)
    r_matrix_sem: np.ndarray   # (n_sem, n_corr) response matrix to monitors
    r_matrix_ap: np.ndarray    # (K, n_corr) response matrix to aperture checkpoints


@dataclass
class PerturbedModel:
    """Full perturbed beamline model."""
    h: PerturbedPlane
    v: PerturbedPlane
    nu: float                  # effective background noise level
    epsilon_h: float           # perturbed geometric emittance in H
    epsilon_v: float           # perturbed geometric emittance in V


def _transport_twiss(
    beta_nom_0: float,
    alpha_nom_0: float,
    beta_nom_s: np.ndarray,
    alpha_nom_s: np.ndarray,
    mu_nom_s: np.ndarray,
    beta_pert_0: float,
    alpha_pert_0: float,
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Transport perturbed initial (beta_0, alpha_0) via nominal transfer matrix M(0 -> s)."""
    dpsi = 2.0 * np.pi * mu_nom_s
    cos_psi = np.cos(dpsi)
    sin_psi = np.sin(dpsi)

    sqrt_ratio = np.sqrt(beta_nom_s / beta_nom_0)
    sqrt_prod = np.sqrt(beta_nom_s * beta_nom_0)

    c = sqrt_ratio * (cos_psi + alpha_nom_0 * sin_psi)
    s = sqrt_prod * sin_psi
    c_prime = -((1.0 + alpha_nom_s * alpha_nom_0) * sin_psi + (alpha_nom_s - alpha_nom_0) * cos_psi) / sqrt_prod
    s_prime = (1.0 / sqrt_ratio) * (cos_psi - alpha_nom_s * sin_psi)

    gamma_pert_0 = (1.0 + alpha_pert_0**2) / beta_pert_0

    beta_pert_s = c**2 * beta_pert_0 - 2.0 * c * s * alpha_pert_0 + s**2 * gamma_pert_0
    beta_pert_s = np.maximum(beta_pert_s, 1.0)

    alpha_pert_s = (
        -c * c_prime * beta_pert_0
        + (c * s_prime + s * c_prime) * alpha_pert_0
        - s * s_prime * gamma_pert_0
    )

    psi_unwrapped = np.unwrap(np.arctan2(s, beta_pert_0 * c - alpha_pert_0 * s))
    psi_unwrapped -= psi_unwrapped[0]
    mu_pert_s = psi_unwrapped / (2.0 * np.pi)

    return beta_pert_s, alpha_pert_s, mu_pert_s


def compute_response_matrix(
    beta_obs: np.ndarray,
    mu_obs: np.ndarray,
    beta_corr: np.ndarray,
    mu_corr: np.ndarray,
) -> np.ndarray:
    """Compute transfer response matrix R_ij according to report eq. (1)."""
    n_obs = len(beta_obs)
    n_corr = len(beta_corr)
    r = np.zeros((n_obs, n_corr), dtype=np.float64)

    for i in range(n_obs):
        for j in range(n_corr):
            if mu_obs[i] > mu_corr[j]:
                dmu = mu_obs[i] - mu_corr[j]
                r[i, j] = np.sqrt(beta_obs[i] * beta_corr[j]) * np.sin(2.0 * np.pi * dmu)
    return r



def create_perturbed_model(
    lattice: Lattice,
    seed: int | None = None,
    spread: str = "medium",
    nominal_nu: float = 0.25,
) -> PerturbedModel:
    """Sample perturbed beamline parameters according to Table 1."""
    if spread == "off":
        r_sem_h = compute_response_matrix(lattice.h.beta_sem, lattice.h.mu_sem, lattice.h.beta_corr, lattice.h.mu_corr)
        r_ap_h = compute_response_matrix(lattice.beta_h_ap, lattice.mu_h_ap, lattice.h.beta_corr, lattice.h.mu_corr)
        r_sem_v = compute_response_matrix(lattice.v.beta_sem, lattice.v.mu_sem, lattice.v.beta_corr, lattice.v.mu_corr)
        r_ap_v = compute_response_matrix(lattice.beta_v_ap, lattice.mu_v_ap, lattice.v.beta_corr, lattice.v.mu_corr)

        pert_h = PerturbedPlane(
            plane="h",
            beta_corr=lattice.h.beta_corr.copy(),
            alpha_corr=lattice.h.alpha_corr.copy(),
            mu_corr=lattice.h.mu_corr.copy(),
            beta_sem=lattice.h.beta_sem.copy(),
            alpha_sem=lattice.h.alpha_sem.copy(),
            mu_sem=lattice.h.mu_sem.copy(),
            beta_ap=lattice.beta_h_ap.copy(),
            alpha_ap=lattice.alpha_h_ap.copy(),
            mu_ap=lattice.mu_h_ap.copy(),
            sigma_sem=lattice.h.sigma_sem.copy(),
            foil_length=lattice.h.foil_length.copy(),
            i_max=lattice.h.i_max.copy(),
            corrector_gains=np.ones(lattice.h.n_corr, dtype=np.float64),
            r_matrix_sem=r_sem_h,
            r_matrix_ap=r_ap_h,
        )

        pert_v = PerturbedPlane(
            plane="v",
            beta_corr=lattice.v.beta_corr.copy(),
            alpha_corr=lattice.v.alpha_corr.copy(),
            mu_corr=lattice.v.mu_corr.copy(),
            beta_sem=lattice.v.beta_sem.copy(),
            alpha_sem=lattice.v.alpha_sem.copy(),
            mu_sem=lattice.v.mu_sem.copy(),
            beta_ap=lattice.beta_v_ap.copy(),
            alpha_ap=lattice.alpha_v_ap.copy(),
            mu_ap=lattice.mu_v_ap.copy(),
            sigma_sem=lattice.v.sigma_sem.copy(),
            foil_length=lattice.v.foil_length.copy(),
            i_max=lattice.v.i_max.copy(),
            corrector_gains=np.ones(lattice.v.n_corr, dtype=np.float64),
            r_matrix_sem=r_sem_v,
            r_matrix_ap=r_ap_v,
        )

        return PerturbedModel(
            h=pert_h,
            v=pert_v,
            nu=nominal_nu,
            epsilon_h=lattice.epsilon,
            epsilon_v=lattice.epsilon,
        )

    rng = np.random.default_rng(seed)

    scale = 0.5 if spread == "low" else (2.0 if spread == "high" else 1.0)

    sigma_gain = 0.02 * scale
    sigma_beta_x0 = 0.50 * scale
    sigma_beta_y0 = 0.10 * scale
    sigma_alpha_x0 = 1.0 * scale
    sigma_alpha_y0 = 0.3 * scale
    sigma_eps = 0.20 * scale
    sigma_nu = 0.40 * scale

    gains_h = np.exp(rng.normal(0.0, sigma_gain, size=lattice.h.n_corr))
    gains_v = np.exp(rng.normal(0.0, sigma_gain, size=lattice.v.n_corr))

    beta_pert_x0 = lattice.beta_h_ap[0] * np.exp(rng.normal(0.0, sigma_beta_x0))
    alpha_pert_x0 = lattice.alpha_h_ap[0] + rng.normal(0.0, sigma_alpha_x0)

    beta_pert_y0 = lattice.beta_v_ap[0] * np.exp(rng.normal(0.0, sigma_beta_y0))
    alpha_pert_y0 = lattice.alpha_v_ap[0] + rng.normal(0.0, sigma_alpha_y0)

    beta_ap_h, alpha_ap_h, mu_ap_h = _transport_twiss(
        lattice.beta_h_ap[0], lattice.alpha_h_ap[0], lattice.beta_h_ap, lattice.alpha_h_ap, lattice.mu_h_ap,
        beta_pert_x0, alpha_pert_x0,
    )

    beta_ap_v, alpha_ap_v, mu_ap_v = _transport_twiss(
        lattice.beta_v_ap[0], lattice.alpha_v_ap[0], lattice.beta_v_ap, lattice.alpha_v_ap, lattice.mu_v_ap,
        beta_pert_y0, alpha_pert_y0,
    )

    beta_corr_h = beta_ap_h[lattice.corr_h_indices_in_ap]
    alpha_corr_h = alpha_ap_h[lattice.corr_h_indices_in_ap]
    mu_corr_h = mu_ap_h[lattice.corr_h_indices_in_ap]

    beta_sem_h = beta_ap_h[lattice.sem_h_indices_in_ap]
    alpha_sem_h = alpha_ap_h[lattice.sem_h_indices_in_ap]
    mu_sem_h = mu_ap_h[lattice.sem_h_indices_in_ap]

    beta_corr_v = beta_ap_v[lattice.corr_v_indices_in_ap]
    alpha_corr_v = alpha_ap_v[lattice.corr_v_indices_in_ap]
    mu_corr_v = mu_ap_v[lattice.corr_v_indices_in_ap]

    beta_sem_v = beta_ap_v[lattice.sem_v_indices_in_ap]
    alpha_sem_v = alpha_ap_v[lattice.sem_v_indices_in_ap]
    mu_sem_v = mu_ap_v[lattice.sem_v_indices_in_ap]

    eps_h = lattice.epsilon * np.exp(rng.normal(0.0, sigma_eps))
    eps_v = lattice.epsilon * np.exp(rng.normal(0.0, sigma_eps))

    sigma_sem_h = np.sqrt(beta_sem_h * eps_h)
    sigma_sem_v = np.sqrt(beta_sem_v * eps_v)

    foil_length_h = lattice.h.foil_length.copy()
    foil_length_v = lattice.v.foil_length.copy()

    i_max_h = 2.0 * ndtr(foil_length_h / sigma_sem_h) - 1.0
    i_max_v = 2.0 * ndtr(foil_length_v / sigma_sem_v) - 1.0

    r_sem_h = compute_response_matrix(beta_sem_h, mu_sem_h, beta_corr_h, mu_corr_h)
    r_ap_h = compute_response_matrix(beta_ap_h, mu_ap_h, beta_corr_h, mu_corr_h)

    r_sem_v = compute_response_matrix(beta_sem_v, mu_sem_v, beta_corr_v, mu_corr_v)
    r_ap_v = compute_response_matrix(beta_ap_v, mu_ap_v, beta_corr_v, mu_corr_v)

    nu_pert = nominal_nu * np.exp(rng.normal(0.0, sigma_nu))

    pert_h = PerturbedPlane(
        plane="h",
        beta_corr=beta_corr_h,
        alpha_corr=alpha_corr_h,
        mu_corr=mu_corr_h,
        beta_sem=beta_sem_h,
        alpha_sem=alpha_sem_h,
        mu_sem=mu_sem_h,
        beta_ap=beta_ap_h,
        alpha_ap=alpha_ap_h,
        mu_ap=mu_ap_h,
        sigma_sem=sigma_sem_h,
        foil_length=foil_length_h,
        i_max=i_max_h,
        corrector_gains=gains_h,
        r_matrix_sem=r_sem_h,
        r_matrix_ap=r_ap_h,
    )

    pert_v = PerturbedPlane(
        plane="v",
        beta_corr=beta_corr_v,
        alpha_corr=alpha_corr_v,
        mu_corr=mu_corr_v,
        beta_sem=beta_sem_v,
        alpha_sem=alpha_sem_v,
        mu_sem=mu_sem_v,
        beta_ap=beta_ap_v,
        alpha_ap=alpha_ap_v,
        mu_ap=mu_ap_v,
        sigma_sem=sigma_sem_v,
        foil_length=foil_length_v,
        i_max=i_max_v,
        corrector_gains=gains_v,
        r_matrix_sem=r_sem_v,
        r_matrix_ap=r_ap_v,
    )

    return PerturbedModel(
        h=pert_h,
        v=pert_v,
        nu=nu_pert,
        epsilon_h=eps_h,
        epsilon_v=eps_v,
    )

